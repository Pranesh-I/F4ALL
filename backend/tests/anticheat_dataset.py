"""Controlled anti-cheat dataset (Sprint 12).

Every case is SYNTHETIC. Pixel-level signals (loops, cuts, repeated frames,
timestamps) come from rendered video encoded to MP4 and decoded again, as the
server does; pose-level signals (people, movement, jumps) come from the parity
fixtures — landmark sequences generated by the mobile test code — edited in a
controlled way. MediaPipe does not detect the rendered figure, so the two
halves are composed rather than extracted from one video.

That makes this *detection validation*: it shows each check fires on the
tampering it is built for and stays quiet on honest input of the same kind. It
says nothing about accuracy on real athletes' recordings.

Every case runs EVERY check, so a check firing where it should not is recorded
as a false flag rather than going unseen. Run it directly for the table:

    python -m tests.anticheat_dataset
"""

