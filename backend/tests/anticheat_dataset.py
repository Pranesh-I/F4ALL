FIXTURES = Path(__file__).parent / "fixtures" / "parity"


# ---------------------------------------------------------------------------
# Inputs
# ---------------------------------------------------------------------------


@dataclass
class VideoSignals:
    hashes: list[int]
    signatures: list[bytes]
    changes: list[float | None]
    timestamps_ms: list[int]
    checksum: str


def decode_signals(path: Path) -> VideoSignals:
    """The pixel-level half of the server's decode pass, without MediaPipe."""
    capture = cv2.VideoCapture(str(path))
    checksum = hashlib.sha256(path.read_bytes()).hexdigest()
    signals = VideoSignals([], [], [], [], checksum)
    previous = None
    index = 0
    while True:
        ok, image = capture.read()
        if not ok:
            break
        signals.hashes.append(perceptual_hash(image))
        signals.signatures.append(frame_signature(image))
        grid = change_grid(image)
        signals.changes.append(
            largest_change(previous, grid) if previous is not None else None
        )
        previous = grid
        signals.timestamps_ms.append(int(index * 1000 / FPS))
        index += 1
    capture.release()
    return signals


def rendered(frames_bgr: list, directory: Path, name: str) -> VideoSignals:
    return decode_signals(write_video(directory / f"{name}.mp4", frames_bgr))


def honest(count: int = 150, start: int = 0) -> list:
    return [draw_scene(index) for index in range(start, start + count)]


def landmarks(sequence: str) -> list[PoseFrame]:
    return decode_sequence((FIXTURES / sequence).read_text(encoding="utf-8"))


def stretch_time(pose: list[PoseFrame], factor: float) -> list[PoseFrame]:
    """The same movement played back `factor` times slower."""
    return [
        replace(frame, timestamp_ms=int(frame.timestamp_ms * factor)) for frame in pose
    ]


def blank(pose: list[PoseFrame], every_other_than: int) -> list[PoseFrame]:
    """Nobody tracked in all but one frame in `every_other_than`."""
    empty = [PosePoint(0.0, 0.0, 0.0, 0.0)] * len(pose[0].points)
    return [
        frame if index % every_other_than == 0 else replace(frame, points=empty)
        for index, frame in enumerate(pose)
    ]


def shift_from(pose: list[PoseFrame], start: int, dx: float) -> list[PoseFrame]:
    """Splice: from `start` on, the athlete is somewhere else in the frame."""
    shifted = []
    for index, frame in enumerate(pose):
        if index >= start:
            frame = replace(
                frame,
                points=[replace(point, x=point.x + dx) for point in frame.points],
            )
        shifted.append(frame)
    return shifted


# ---------------------------------------------------------------------------
# Cases
# ---------------------------------------------------------------------------


@dataclass
class Case:
    name: str
    tampering: str
    expected: set[str]
    test_code: str = "SQUATS"
    sequence: str = "squats_5_clean.csv"
    video: str = "honest"
    pose_transform: object = None
    pose_counts: object = None  # callable(len) -> list[int]
    metadata_overrides: dict = field(default_factory=dict)
    device_score: float | None = None  # None: the server's own score
    height_cm: float | None = None
    face_similarity: float | None = None  # None: no registration photo
    duplicate_of: str | None = None  # "identical", "reencoded", "other_take"
    # Flags that are a correct consequence of the tampering, not the check
    # under test (a video with nobody in it cannot be scored either).
    also_expected: set[str] = field(default_factory=set)
    # False flags that fire here and are understood, with why. Still counted
    # and shown as false flags; listed so a NEW one fails the test.
    known_false_flags: set[str] = field(default_factory=set)
    note: str = ""


def cases() -> list[Case]:
    return [
        Case("normal", "none (honest control)", set()),
        Case("looped", "a 2 s stretch copied back in", {"looped_frames"}, video="looped"),
        Case("duplicated_frames", "every frame written twice (2x slow motion)",
             {"duplicate_frames"}, video="doubled",
             known_false_flags={"looped_frames"},
             note="looped_frames: the rendered figure repeats exactly within a rep; "
                  "doubling stretches those repeats past the 20-frame minimum run"),
        Case("wrong_person", "video face does not match the registration photo",
             {"face_mismatch"}, face_similarity=0.20),
        Case("multiple_people", "a second person in 40% of frames",
             {"multiple_people"},
             pose_counts=lambda n: [2 if i % 5 < 2 else 1 for i in range(n)]),
        Case("no_person", "athlete tracked in 1 frame in 5", {"no_subject"},
             pose_transform=lambda pose: blank(pose, 5),
             also_expected={"server_could_not_score"}),
        Case("cut_video", "a different scene spliced in", {"abrupt_cut"},
             video="spliced"),
        Case("timestamp_gap", "0.6 s of timeline removed", {"timestamp_anomaly"},
             video="gap"),
        Case("wrong_duration", "container says 2.5 s for a squat test",
             {"duration_implausible"}, metadata_overrides={"duration_seconds": 2.5}),
        Case("sped_up_reps", "reps faster than the physical minimum",
             {"impossible_movement"}, sequence="squats_fast.csv",
             metadata_overrides={"duration_seconds": 30.0}),
        Case("slowed_jump", "40 cm jump played at half speed",
             {"playback_speed_suspicious"}, test_code="VERTICAL_JUMP",
             sequence="jump_40cm.csv", height_cm=170.0,
             pose_transform=lambda pose: stretch_time(pose, 2.0),
             metadata_overrides={"duration_seconds": 30.0},
             known_false_flags={"subject_swapped"},
             note="subject_swapped: the synthetic jump fixture is not physical "
                  "(its apparent size jumps 89% at take-off); it fires on the "
                  "unmodified fixture too"),
        Case("frame_rate_mismatch", "declares 30 fps, frames timed at 60 fps",
             {"playback_speed_suspicious"},
             pose_transform=lambda pose: stretch_time(pose, 0.5),
             also_expected={"impossible_movement"}),
        Case("landmark_teleport", "athlete jumps a body-width sideways and stays",
             {"impossible_movement"},
             pose_transform=lambda pose: shift_from(pose, 90, 0.35)),
        Case("score_mismatch", "phone claims 12 reps, video shows 5",
             {"score_discrepancy"}, device_score=12),
        Case("duplicate_identical", "the same file submitted again",
             {"duplicate_submission"}, duplicate_of="identical"),
        Case("duplicate_reencoded", "the same footage re-encoded",
             {"duplicate_submission"}, duplicate_of="reencoded"),
        Case("other_take_same_room", "a different recording, same place (control)",
             set(), duplicate_of="other_take"),
    ]


