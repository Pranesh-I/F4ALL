# Running
# ---------------------------------------------------------------------------


@dataclass
class Outcome:
    case: Case
    fired: list[str]
    flags: list[finalization.FlagSpec]
    verdict: str
    summaries: dict

    @property
    def detected(self) -> bool:
        return self.case.expected <= set(self.fired)

    @property
    def missed(self) -> set[str]:
        return self.case.expected - set(self.fired)

    @property
    def false_flags(self) -> set[str]:
        return set(self.fired) - self.case.expected - self.case.also_expected


def _video(kind: str, directory: Path) -> VideoSignals:
    base = honest()
    if kind == "looped":
        return rendered(base[:90] + base[30:90] + base[90:], directory, kind)
    if kind == "doubled":
        return rendered([f for f in base for _ in (0, 1)], directory, kind)
    if kind == "spliced":
        other = [draw_scene(i, subject_scale=0.6) for i in range(75)]
        dark = [(f * 0.35).astype("uint8") for f in other]
        return rendered(base[:75] + dark, directory, kind)
    signals = rendered(base, directory, "honest")
    if kind == "gap":
        signals.timestamps_ms = [
            t + (600 if i >= 75 else 0) for i, t in enumerate(signals.timestamps_ms)
        ]
    return signals


def _candidate(
    kind: str, directory: Path, signals: VideoSignals
) -> duplicates.Candidate:
    if kind == "identical":
        checksum, other = signals.checksum, signals
    elif kind == "reencoded":
        capture = cv2.VideoCapture(str(directory / "honest.mp4"))
        frames_bgr = []
        while True:
            ok, image = capture.read()
            if not ok:
                break
            smaller = cv2.resize(image, (360, 640))
            frames_bgr.append(cv2.resize(smaller, (WIDTH, HEIGHT)))
        other = rendered(frames_bgr, directory, "reencoded")
        checksum = other.checksum
    else:
        other = rendered(honest(150, start=150), directory, "other_take")
        checksum = other.checksum
    return duplicates.Candidate(
        result_id=uuid.UUID(int=1),
        athlete_id=uuid.UUID(int=2),
        session_id=uuid.UUID(int=3),
        test_code="SQUATS",
        status="verified",
        checksum_sha256=checksum,
        fingerprint=duplicates.fingerprint(other.signatures),
    )


def run_case(case: Case, directory: Path) -> Outcome:
    limits = IntegrityLimits()
    signals = _video(case.video, directory)

    pose = landmarks(case.sequence)
    if case.pose_transform is not None:
        pose = case.pose_transform(pose)
    counts = case.pose_counts(len(pose)) if case.pose_counts else [1] * len(pose)

    meta = VideoMetadata(
        duration_seconds=len(pose) / FPS,
        width=WIDTH,
        height=HEIGHT,
        fps=float(FPS),
        file_size_bytes=2_000_000,
        frame_count=len(pose),
    )
    meta = replace(meta, **case.metadata_overrides)

    report = CheatReport()
    metadata.check_metadata(meta, case.test_code, report=report)
    frames.check_frames(
        signals.hashes,
        signals.signatures,
        signals.timestamps_ms,
        report=report,
        frame_changes=signals.changes,
    )
    subject.check_subject(pose, counts, report=report)

    if case.face_similarity is not None:
        comparison = face.FaceComparison(case.face_similarity, 10, 12)
        with mock.patch.object(face, "compare_faces", return_value=comparison):
            face.check_face(
                Path("video.mp4"), Path("reference.jpg"), Path("."), report=report
            )
    else:
        face.check_face(Path("video.mp4"), None, Path("."), report=report)

    finding = identity_finding(official=False, outcome=None)
    if finding is not None:
        report.add(finding)
    report.summarise(
        "identity",
        identity_summary(official=False, pre_test=None, face=report.face,
                         face_skipped=report.skipped.get("face_mismatch")),
    )

    server_result = analyze_sequence(
        build_analyzer(TestType(case.test_code), case.height_cm), pose
    )
    run_analysis_checks(
        report, pose_frames=pose, server_result=server_result, video_metadata=meta,
        limits=limits,
    )

    candidates = []
    if case.duplicate_of is not None:
        candidates.append(_candidate(case.duplicate_of, directory, signals))
    duplicates.check_duplicates(
        athlete_id=uuid.UUID(int=9),
        session_id=uuid.UUID(int=3),
        checksum_sha256=signals.checksum,
        video_fingerprint=duplicates.fingerprint(signals.signatures),
        candidates=candidates,
        report=report,
    )

    comparison = discrepancy.evaluate(
        server_result=server_result,
        device_score=(
            case.device_score if case.device_score is not None else server_result.score
        ),
        settings=Settings(),
    )
    decision = finalization.decide(
        server_result=server_result, comparison=comparison, cheat_report=report
    )
    return Outcome(
        case=case,
        fired=[flag.reason for flag in decision.flags],
        flags=decision.flags,
        verdict=decision.verdict.value,
        summaries=report.summaries,
    )


def run_all(directory: Path | None = None) -> list[Outcome]:
    if directory is not None:
        return [run_case(case, directory) for case in cases()]
    with tempfile.TemporaryDirectory(prefix="f4all-anticheat-") as temporary:
        return [run_case(case, Path(temporary)) for case in cases()]


def table(outcomes: list[Outcome]) -> str:
    lines = [
        "| case | tampering | expected | detected | missed | false flags | verdict "
        "| note |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for o in outcomes:
        lines.append(
            f"| {o.case.name} | {o.case.tampering} | "
            f"{', '.join(sorted(o.case.expected)) or '-'} | "
            f"{'yes' if o.detected else 'NO'} | {', '.join(sorted(o.missed)) or '-'} | "
            f"{', '.join(sorted(o.false_flags)) or '-'} | {o.verdict} | "
            f"{o.case.note or '-'} |"
        )
    return "\n".join(lines)


if __name__ == "__main__":  # pragma: no cover
    results = run_all()
    print(table(results))
    print()
    for outcome in results:
        for flag in outcome.flags:
            print(f"{outcome.case.name}: {flag.reason} [{flag.severity}] {flag.detail}")
            print(f"    evidence: {flag.evidence}")
